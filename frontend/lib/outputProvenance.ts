import type { AutoRebalanceJobDetailResponse } from "@/types/api";

function modelFamily(value: string): string | null {
  if (/deepseek/i.test(value)) return "deepseek";
  if (/claude|anthropic/i.test(value)) return "anthropic";
  if (/gemini|google/i.test(value)) return "google";
  if (/\bgpt\b|openai|\bo[134](?:\b|[- ])/i.test(value)) return "openai";
  if (/grok|xai|x\.ai/i.test(value)) return "xai";
  return null;
}

export function outputAttribution(job: AutoRebalanceJobDetailResponse) {
  // Inspect explicit header declarations only, never arbitrary mentions in advice.
  const header = (job.response || "").slice(0, 4096).split(/\r?\n/).slice(0, 24)
    .map(line => line.replace(/[*`]/g, "").trim())
    .find(line => /^(?:#{1,6}\s*)?(?:model(?:\s+(?:used|name))?|llm|generated by)\s*[:|–—-]\s*\S/i.test(line));
  const identities = job.output_provenance?.source === "api_usage_attempt_events"
    ? job.output_provenance.identities : [];
  const declaredFamily = header ? modelFamily(header) : null;
  // A family difference is definite; unknown names and aliases are not guessed.
  const evidence = identities.length ? identities : [{ provider: job.provider, model: job.model }];
  const conflict = Boolean(declaredFamily && evidence.every(identity => {
    const family = modelFamily(`${identity.provider} ${identity.model || ""}`);
    return family !== null && family !== declaredFamily;
  }));
  return { header, identities, conflict, comparison: identities.length ? "telemetry" : "requested" };
}
