#!/usr/bin/env node

import { writeFile } from "node:fs/promises";
import path from "node:path";

const [target, buildSha, buildTimestamp] = process.argv.slice(2);
if (!target || !buildSha || !buildTimestamp) {
  console.error(
    "Usage: stamp-frontend-build.mjs <generatedBuildInfo.ts> <build-sha> <ISO timestamp>",
  );
  process.exit(1);
}
if (!/^[0-9a-f]{40}$/i.test(buildSha)) {
  console.error("Build SHA must be a 40-character Git SHA.");
  process.exit(1);
}
if (Number.isNaN(Date.parse(buildTimestamp))) {
  console.error("Build timestamp must be a valid ISO timestamp.");
  process.exit(1);
}

await writeFile(
  path.resolve(target),
  [
    "// Generated by the production deployment workflow.",
    `export const GENERATED_BUILD_SHA = ${JSON.stringify(buildSha)};`,
    `export const GENERATED_BUILD_TIMESTAMP: string | null = ${JSON.stringify(buildTimestamp)};`,
    "",
  ].join("\n"),
  "utf8",
);
